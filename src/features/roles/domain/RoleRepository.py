from __future__ import annotations
from typing import Protocol
from src.features.roles.domain.entities.Role import Role


class RoleRepository(Protocol):
    def get(self, role_id: str) -> Role: ...
    def list(self) -> list[Role]: ...
    def create(self, name: str, permissions: list[str], actor_id: str) -> Role: ...
    def update(self, role_id: str, name: str, permissions: list[str], actor_id: str) -> Role: ...
    def delete(self, role_id: str, actor_id: str) -> None: ...

