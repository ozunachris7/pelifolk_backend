from typing import Protocol
from .dto import AnimalInput, AnimalPage, AnimalResponse, BreedResponse


class AnimalRepository(Protocol):
    def list(self, q: str, sex: str | None, offset: int, limit: int, exclude_id: str | None) -> AnimalPage: ...
    def get(self, animal_id: str) -> AnimalResponse: ...
    def save(self, data: AnimalInput, actor_id: str, animal_id: str | None) -> AnimalResponse: ...
    def breeds(self) -> list[BreedResponse]: ...
    def create_breed(self, name: str, actor_id: str) -> BreedResponse: ...
    def update_breed(self, breed_id: int, name: str, actor_id: str) -> BreedResponse: ...
    def delete_breed(self, breed_id: int, actor_id: str) -> None: ...
