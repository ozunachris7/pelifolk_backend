from typing import Protocol
from src.features.users.domain.entities.User import User
from src.features.roles.domain.entities.Role import Role


class UserRepository(Protocol):
    def get_role(self, role_id: str) -> Role: ...
    def list(self, offset: int, limit: int) -> list[User]: ...
    def get(self, user_id: str) -> User: ...
    def create(self, values: dict, actor_id: str) -> User: ...
    def update(self, user_id: str, values: dict, actor_id: str) -> User: ...
