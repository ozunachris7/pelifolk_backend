CREATE TABLE IF NOT EXISTS treatment_doses (
  id CHAR(36) PRIMARY KEY,
  treatment_event_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  applied_at_utc DATETIME NOT NULL,
  clinical_date DATE NOT NULL,
  utc_offset_minutes INT NOT NULL,
  administered_by VARCHAR(190) NOT NULL,
  dose_value DECIMAL(10,3) NOT NULL,
  dose_unit_id SMALLINT UNSIGNED NOT NULL,
  route_id SMALLINT UNSIGNED NOT NULL,
  notes TEXT,
  is_deviation BOOLEAN NOT NULL DEFAULT FALSE,
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_treatment_dose_time (treatment_event_id, product_id, applied_at_utc),
  FOREIGN KEY (treatment_event_id, product_id) REFERENCES event_treatments(event_id, product_id),
  FOREIGN KEY (dose_unit_id) REFERENCES units(id),
  FOREIGN KEY (route_id) REFERENCES administration_routes(id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (role_id) REFERENCES roles(id),
  CHECK (dose_value > 0)
);
