CREATE TABLE IF NOT EXISTS animal_incidents (
  id CHAR(36) PRIMARY KEY,
  animal_id CHAR(36) NOT NULL,
  date DATE NOT NULL,
  kind VARCHAR(30) NOT NULL,
  description TEXT NOT NULL,
  location VARCHAR(190),
  initial_actions TEXT,
  health_case_id CHAR(36),
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  version INT NOT NULL DEFAULT 0,
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (animal_id) REFERENCES animals(id),
  FOREIGN KEY (health_case_id) REFERENCES health_cases(id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (role_id) REFERENCES roles(id),
  CHECK (kind IN ('accident','abortion','attack','poisoning','disappearance','other')),
  CHECK (status IN ('open','in_progress','closed')),
  CHECK (version >= 0),
  KEY ix_incidents_animal_date (animal_id, date),
  KEY ix_incidents_date (date)
);

CREATE TABLE IF NOT EXISTS incident_followups (
  id CHAR(36) PRIMARY KEY,
  incident_id CHAR(36) NOT NULL,
  date DATE NOT NULL,
  notes TEXT NOT NULL,
  status VARCHAR(20) NOT NULL,
  version INT NOT NULL,
  health_case_id CHAR(36),
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (incident_id) REFERENCES animal_incidents(id),
  FOREIGN KEY (health_case_id) REFERENCES health_cases(id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (role_id) REFERENCES roles(id),
  CHECK (status IN ('open','in_progress','closed')),
  CHECK (version > 0),
  UNIQUE KEY uq_incident_followup_version (incident_id, version),
  KEY ix_incident_followups_date (incident_id, date)
);
