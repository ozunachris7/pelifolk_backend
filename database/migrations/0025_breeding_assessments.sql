CREATE TABLE IF NOT EXISTS breeding_assessments (
  id CHAR(36) PRIMARY KEY,
  birth_event_id CHAR(36) NOT NULL,
  animal_id CHAR(36) NOT NULL,
  mother_id CHAR(36) NOT NULL,
  father_id CHAR(36),
  kind VARCHAR(20) NOT NULL,
  date DATE NOT NULL,
  evaluated_by VARCHAR(190) NOT NULL,
  rubric_version VARCHAR(40) NOT NULL,
  findings JSON NOT NULL,
  notes TEXT,
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (birth_event_id) REFERENCES event_births(event_id),
  FOREIGN KEY (animal_id) REFERENCES animals(id),
  FOREIGN KEY (mother_id) REFERENCES animals(id),
  FOREIGN KEY (father_id) REFERENCES animals(id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (role_id) REFERENCES roles(id),
  CHECK (kind IN ('maternal', 'offspring')),
  KEY ix_assessments_animal_date (animal_id, date),
  KEY ix_assessments_mother_date (mother_id, date),
  KEY ix_assessments_father_date (father_id, date),
  KEY ix_assessments_birth (birth_event_id)
);
