CREATE TABLE IF NOT EXISTS animal_reactions (
  id CHAR(36) PRIMARY KEY,
  animal_id CHAR(36) NOT NULL,
  date DATE NOT NULL,
  kind VARCHAR(30) NOT NULL,
  description TEXT NOT NULL,
  suspected_agent VARCHAR(190),
  product_id CHAR(36),
  dose_id CHAR(36),
  user_id CHAR(36) NOT NULL,
  role_id CHAR(36) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_date DATE,
  closure_notes TEXT,
  closed_by CHAR(36),
  closure_role_id CHAR(36),
  closed_at DATETIME,
  FOREIGN KEY (animal_id) REFERENCES animals(id),
  FOREIGN KEY (product_id) REFERENCES products(id),
  FOREIGN KEY (dose_id) REFERENCES treatment_doses(id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (role_id) REFERENCES roles(id),
  FOREIGN KEY (closed_by) REFERENCES users(id),
  FOREIGN KEY (closure_role_id) REFERENCES roles(id),
  CHECK (kind IN ('suspected_allergy', 'adverse_reaction')),
  CHECK (closed_date IS NULL OR closed_date >= date),
  CHECK ((closed_date IS NULL AND closure_notes IS NULL AND closed_by IS NULL AND closure_role_id IS NULL AND closed_at IS NULL)
      OR (closed_date IS NOT NULL AND closure_notes IS NOT NULL AND closed_by IS NOT NULL AND closure_role_id IS NOT NULL AND closed_at IS NOT NULL)),
  KEY ix_reactions_animal_date (animal_id, date),
  KEY ix_reactions_date (date)
);
